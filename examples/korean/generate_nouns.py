"""Regenerate the bounded Korean noun tables from the attributed NIKL list."""
import argparse
import csv
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "algorithms/korean.sbl"
LEXICON = Path(__file__).resolve().parent / "lexicon/nouns.tsv"
BEGIN = "// BEGIN GENERATED COMMON NOUNS"
END = "// END GENERATED COMMON NOUNS"
# A complete noun as well as 역사 + 가. Preserve the ambiguous isolated word.
PROTECTED = {"역사가"}
CHUNK_SIZE = 16


def literal(word):
    return "'" + "".join("{n%04X}" % ord(c) for c in word) + "'"


def generate():
    with LEXICON.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    nouns = sorted({r["lemma"] for r in rows})
    if len(nouns) != 377 or any(not re.fullmatch("[가-힣]{2,5}", w) for w in nouns):
        raise ValueError("Expected the reviewed 377 new Hangul noun candidates")
    chars = sorted(set("".join(nouns) + "이가을를"))
    lines = [BEGIN,
             "// Generated by examples/korean/generate_nouns.py; do not edit this block.",
             "// NIKL Korean Learners' List (2003), KOGL Type 1 attribution:",
             "// see examples/korean/lexicon/COPYING and source.json."]
    lines += ["stringdef n%04X '{U+%04X}'" % (ord(c), ord(c)) for c in chars]
    lines += ["", "define noun_common as ("]
    for word in sorted(PROTECTED):
        lines.append("    not (%s atlimit) // %s: also an intact noun" % (literal(word), word))
    lines += ["    // Bound each among table to avoid sparse Unicode wide-table overflow."]
    groups = []
    for consonant in (False, True):
        subset = [w for w in nouns if bool((ord(w[-1]) - 0xAC00) % 28) == consonant]
        for start in range(0, len(subset), CHUNK_SIZE):
            groups.append((subset[start:start + CHUNK_SIZE], "이을" if consonant else "가를"))
    for i, (chunk, suffixes) in enumerate(groups):
        lines.append("    ( among (" if i == 0 else "    ) or ( among (")
        lines += ["        %s // %s" % (literal(w), w) for w in chunk]
        lines += ["    )", "      [ among (%s %s) ]" % tuple(literal(c) for c in suffixes),
                  "      atlimit delete"]
    lines += ["    )", ")", END]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = SOURCE.read_text(encoding="utf-8")
    start, end = source.index(BEGIN), source.index(END) + len(END)
    generated = source[:start] + generate() + source[end:]
    if args.check:
        if generated != source:
            parser.exit(1, "Korean noun tables are stale; run examples/korean/generate_nouns.py\n")
    else:
        SOURCE.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
